// ---------------------------------------------------------------------------
// Tool intent cache — pre-generated by tools/generate-tool-intents.ts
// ---------------------------------------------------------------------------
// Maps tool name → { text, enriched } where enriched = text + Intent: keywords.
// When cache exists, IntentEnricher is replaced with NoopDocumentEnricher
// and enriched text is passed directly to upsert (no LLM calls at startup).
// ---------------------------------------------------------------------------
let toolIntentCache: Record<string, { text: string; enriched: string }> | null =
  null;

function getToolIntentCache(): typeof toolIntentCache {
  if (toolIntentCache !== undefined && toolIntentCache !== null)
    return toolIntentCache;
  const cachePath = path.resolve(__dirname, 'tool-intents.json');
  try {
    if (fs.existsSync(cachePath)) {
      const parsed = JSON.parse(fs.readFileSync(cachePath, 'utf-8'));
      toolIntentCache = parsed;
      cds.log('agent-manager').info('Loaded tool intent cache', {
        entries: Object.keys(parsed).length,
      });
    } else {
      toolIntentCache = null;
    }
  } catch {
    toolIntentCache = null;
  }
  return toolIntentCache;
}

// ---------------------------------------------------------------------------
// ExpositionFilteringRag — wraps tools store with role-based filtering
// ---------------------------------------------------------------------------
// Tools are vectorized with metadata.exposition = group name (readonly, high, etc.).
// On query, strips the user/destination namespace (tools have no namespace) but
// post-filters results to only return tools whose exposition is in the caller's
// allowed set (from ragFilter.exposition).
// If ragFilter.exposition is not set, all tools are returned (backwards compat).
// ---------------------------------------------------------------------------

// Cap how many `skill:*` entries a single RAG query may surface. Skills and tools
// live in the SAME shared store and compete for the same top-K, so without a cap a
// RAP prompt (all 18 skills are RAP-adjacent) fills most of the top-K with skills and
// starves tool selection — observed live: 12 of 15 slots were skills. We give tools
// their full k and limit skills to the top-N by score. Env-tunable
// (`LLM_AGENT_SKILL_RAG_K`, default 3); 0 disables skill injection.
const SKILL_RAG_K = (() => {
  const parsed = Number(process.env.LLM_AGENT_SKILL_RAG_K);
  return Number.isFinite(parsed) ? Math.max(0, Math.trunc(parsed)) : 3;
})();

const isSkillId = (id: unknown): boolean =>
  typeof id === 'string' && id.startsWith('skill:');

export class ExpositionFilteringRag implements IRag, IRagEditor {
  constructor(private inner: IRag) {}

  // Skill ids (`skill:<name>`) already vectorized into THIS shared store. The
  // llm-agent builder re-runs its skill-vectorization loop on every build(), and
  // buildAgentForDestination calls build() once per destination against the SAME
  // shared store — so without this, the 18 skills get re-embedded N times
  // (VectorRag.upsert embeds first, then idempotent-replaces by id), reintroducing
  // embedding calls on the deliberately embedding-free cold-start path (v6.21.0).
  // The text for a given skill id is fixed within a process, so a second upsert of
  // the same id is pure waste — skip it. delete/clear reset the guard so an edited
  // skill re-vectorizes.
  private readonly vectorizedSkillIds = new Set<string>();

  async upsert(
    text: string,
    metadata: Record<string, unknown>,
    options?: CallOptions,
  ) {
    const writer = this.inner.writer?.();
    if (!writer) throw new Error('Inner RAG is not editable');
    const { id: rawId, ...rest } = metadata;
    const id = typeof rawId === 'string' ? rawId : '';
    if (!id) throw new Error('metadata.id is required for upsert');
    const res = await writer.upsertRaw(id, text, rest, options);
    if (!res.ok) return res;
    return { ok: true as const, value: { id } };
  }

  async deleteById(id: string, options?: CallOptions) {
    const writer = this.inner.writer?.();
    if (!writer) throw new Error('Inner RAG is not editable');
    return writer.deleteByIdRaw(id, options);
  }

  async getById(id: string, options?: CallOptions) {
    return this.inner.getById(id, options);
  }

  writer(): IRagBackendWriter | undefined {
    const inner = this.inner.writer?.();
    if (!inner) return undefined;
    const seen = this.vectorizedSkillIds;
    // Dedup skill:* re-vectorization (see vectorizedSkillIds above). Everything
    // else passes straight through.
    return {
      async upsertRaw(id, text, metadata, options) {
        if (id.startsWith('skill:') && seen.has(id)) {
          return { ok: true as const, value: undefined };
        }
        const res = await inner.upsertRaw(id, text, metadata, options);
        if (res.ok && id.startsWith('skill:')) seen.add(id);
        return res;
      },
      async deleteByIdRaw(id, options) {
        if (id.startsWith('skill:')) seen.delete(id);
        return inner.deleteByIdRaw(id, options);
      },
      ...(inner.clearAll && {
        clearAll: async () => {
          seen.clear();
          // biome-ignore lint/style/noNonNullAssertion: guarded by the spread condition
          return inner.clearAll!();
        },
      }),
      ...(inner.upsertPrecomputedRaw && {
        upsertPrecomputedRaw: async (
          id: string,
          text: string,
          vector: number[],
          metadata: RagMetadata,
          options?: CallOptions,
        ) => {
          // biome-ignore lint/style/noNonNullAssertion: guarded by the spread condition
          const res = await inner.upsertPrecomputedRaw!(
            id,
            text,
            vector,
            metadata,
            options,
          );
          if (res.ok && id.startsWith('skill:')) seen.add(id);
          return res;
        },
      }),
    };
  }

  async query(
    embedding: IQueryEmbedding,
    k: number,
    options?: {
      signal?: AbortSignal;
      ragFilter?: { namespace?: string; exposition?: string[] };
    },
  ) {
    const log = cds.log('tool-rag');
    const allowedExpositions = options?.ragFilter?.exposition;
    // Strip ragFilter — tools use exposition metadata, not namespace
    const { ragFilter: _unused, ...cleanOpts } = options ?? {};
    // Over-fetch so that (a) exposition post-filtering doesn't starve results and
    // (b) tools crowded out of the top-K by skills can be recovered before the cap.
    // A fixed multiplier is not enough: if every skill outranks the tools, the top
    // k*3 could be all skills and tools would never be fetched. We know exactly how
    // many skills live in this store (the writer tracks them), so add that headroom
    // to GUARANTEE k tools are reachable even when all skills rank first.
    const overFetchK = k * 3 + this.vectorizedSkillIds.size;
    const result = await this.inner.query(embedding, overFetchK, cleanOpts);

    // Give tools their full k budget; cap skills at the top SKILL_RAG_K by score.
    // Input rows are score-descending from the inner store, so slicing keeps the best.
    const capSkills = (rows: RagResult[]) => {
      const tools = rows.filter((r) => !isSkillId(r.metadata.id)).slice(0, k);
      const skills = rows
        .filter((r) => isSkillId(r.metadata.id))
        .slice(0, SKILL_RAG_K);
      return [...tools, ...skills];
    };

    if (result.ok) {
      log.debug('RAG tool search results', {
        k,
        overFetchK,
        totalResults: result.value.length,
        exposition: allowedExpositions ?? 'all',
        results: result.value.map((r) => ({
          id: r.metadata.id,
          score: Math.round(r.score * 1000) / 1000,
          exposition: r.metadata.exposition ?? 'none',
        })),
      });
    }

    if (!result.ok) return result;
    // No role filter (e.g. no exposition passed): still cap skills so they can't
    // crowd tools, but skip exposition post-filtering.
    if (!allowedExpositions) {
      return { ok: true as const, value: capSkills(result.value) };
    }

    // Post-filter by allowed exposition levels. A tool WITHOUT an exposition
    // tag is excluded when a role filter is active — otherwise an un-tagged tool
    // (e.g. a group not mapped in getToolExpositionMap) would bypass role-based
    // filtering and reach every role. Every exposed tool must carry an exposition.
    const allowed = new Set(allowedExpositions);
    const filtered = result.value.filter((r) => {
      // Skills are instruction TEXT, not callable tools. `exposition` gates tool
      // ACCESS; a skill cannot be invoked, so role-filtering it would only hide
      // rules while changing nothing about what the caller may do. The builder
      // upserts them with empty metadata (`upsertRaw('skill:<name>', text, {})`),
      // so without this they would all be dropped and skill injection would
      // silently do nothing. Narrow on purpose: ONLY the `skill:` prefix — an
      // untagged TOOL must still be dropped (the v6.22.0 bypass fix).
      const id = r.metadata.id;
      if (typeof id === 'string' && id.startsWith('skill:')) {
        // A skill is instruction TEXT, not a callable tool — but a WRITE skill
        // (creating-*/activating-*) handed to a read-only caller makes the
        // executor narrate a create it cannot perform (no write tool is granted),
        // fabricating success. So a TAGGED skill is gated by the SAME exposition
        // as the tools it drives; an UNtagged skill still passes (harmless
        // instructions — preserves the default for any future/consumer skill).
        const skillExpo = SKILL_EXPOSITIONS[id.slice('skill:'.length)];
        return !skillExpo || allowed.has(skillExpo);
      }
      return (
        !!r.metadata.exposition && allowed.has(r.metadata.exposition as string)
      );
    });

    if (filtered.length < result.value.length) {
      log.debug('RAG tool search filtered by exposition', {
        before: result.value.length,
        after: filtered.length,
        removed: result.value
          .filter(
            (r) =>
              r.metadata.exposition &&
              !allowed.has(r.metadata.exposition as string),
          )
          .map((r) => r.metadata.id),
      });
    }

    return { ok: true as const, value: capSkills(filtered) };
  }

  async healthCheck() {
    return this.inner.healthCheck();
  }
}

// ---------------------------------------------------------------------------
// Tool → exposition group mapping
// ---------------------------------------------------------------------------
// Each tool belongs to exactly one exposition group (readonly, high, search,
// system, compact). Built once at startup from handler group instances.
// Used to tag tools in RAG metadata for role-based filtering.
// ---------------------------------------------------------------------------

let toolExpositionMap: Map<string, string> | null = null;

function getToolExpositionMap(): Map<string, string> {
  if (toolExpositionMap) return toolExpositionMap;

  const noopCtx: HandlerContext = {
    connection: null as unknown as HandlerContext['connection'],
    logger: loggerAdapter,
  };

  const groups: Array<{
    name: string;
    group: {
      getHandlers(): Array<{
        toolDefinition?: { name: string };
        definition?: { name: string };
      }>;
    };
  }> = [
    { name: 'readonly', group: new ReadOnlyHandlersGroup(noopCtx) },
    { name: 'high', group: new HighLevelHandlersGroup(noopCtx) },
    { name: 'search', group: new SearchHandlersGroup(noopCtx) },
    { name: 'system', group: new SystemHandlersGroup(noopCtx) },
    { name: 'compact', group: new CompactHandlersGroup(noopCtx) },
    // Low-level generic handlers get their own restricted 'low' exposition so
    // they are role-gated (granted only to MCP_Full) instead of falling through
    // as un-tagged tools that bypass ExpositionFilteringRag's role filter.
    { name: 'low', group: new LowLevelHandlersGroup(noopCtx) },
  ];

  toolExpositionMap = new Map();
  for (const { name, group } of groups) {
    for (const h of group.getHandlers()) {
      const toolName = h.toolDefinition?.name ?? h.definition?.name ?? '';
      if (toolName && !toolExpositionMap.has(toolName)) {
        toolExpositionMap.set(toolName, name);
      }
    }
  }
  for (const [t, e] of Object.entries(CLOUD_LOCAL_TOOL_EXPOSITIONS)) {
    toolExpositionMap.set(t, e);
  }

  cds.log('agent-manager').info('Built tool exposition map', {
    total: toolExpositionMap.size,
    readonly: [...toolExpositionMap.values()].filter((v) => v === 'readonly')
      .length,
    high: [...toolExpositionMap.values()].filter((v) => v === 'high').length,
    search: [...toolExpositionMap.values()].filter((v) => v === 'search')
      .length,
    system: [...toolExpositionMap.values()].filter((v) => v === 'system')
      .length,
    compact: [...toolExpositionMap.values()].filter((v) => v === 'compact')
      .length,
    low: [...toolExpositionMap.values()].filter((v) => v === 'low').length,
  });

  return toolExpositionMap;
}

