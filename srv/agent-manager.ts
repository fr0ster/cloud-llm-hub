/**
 * Initialize a single destination: build MCP adapter, vectorize tools, build SmartAgent.
 * Updates destinationStates map and agentHandles map.
 */
async function initDestination(
  destinationName: string,
): Promise<DestinationState> {
  const log = cds.log('agent-manager');
  const config = getAgentConfig();

  log.info('Initializing destination', { destination: destinationName });

  // Carry destination metadata (proxyType/auth) so the UI can prompt for SAP
  // credentials on connect for on-premise destinations. Preserve any value
  // already set by the pre-populate pass.
  const prev = destinationStates.get(destinationName);
  let proxyType = prev?.proxyType;
  let requiresCredentials = prev?.requiresCredentials;
  if (proxyType === undefined) {
    try {
      const meta = (await getAvailableDestinations()).find(
        (d) => d.name === destinationName,
      );
      if (meta) {
        proxyType = meta.proxyType;
        requiresCredentials = destinationRequiresCredentials(
          meta.proxyType,
          meta.authentication,
        );
      }
    } catch {
      // Non-fatal: UI falls back to the 401 SAP_CREDENTIALS_REQUIRED prompt.
    }
  }

  // Shared tool corpus — vectorized ONCE and reused by every destination
  // (destination-independent). This replaces the former per-destination
  // vectorization; the first caller triggers the build, the rest share it.
  const sharedRag = await ensureSharedToolsVectorized();

  const state: DestinationState = {
    mcpAdapter: null,
    toolsRag: sharedRag,
    toolCount: sharedToolCount,
    status: 'vectorizing',
    proxyType,
    requiresCredentials,
  };
  destinationStates.set(destinationName, state);

  try {
    state.mcpAdapter = await buildEmbeddedMcpAdapter(destinationName);

    // Build a full SmartAgent for this destination, referencing the SHARED
    // tool RAG (no per-destination re-vectorization).
    const handle = await buildAgentForDestination(
      state.mcpAdapter,
      sharedRag,
      config,
    );
    agentHandles.set(destinationName, handle);
    state.status = 'ready';
    log.info('Destination ready', {
      destination: destinationName,
      toolCount: state.toolCount,
    });
  } catch (err) {
    const errorMsg = err instanceof Error ? err.message : String(err);
    state.error = errorMsg;
    // Distinguish unreachable (probe failed) from other init errors
    if (errorMsg.includes('unreachable')) {
      state.status = 'unreachable';
      log.warn('Destination unreachable, skipping', {
        destination: destinationName,
        error: errorMsg,
      });
    } else {
      state.status = 'error';
      log.error('Destination initialization failed', {
        destination: destinationName,
        error: errorMsg,
      });
    }
  }

  return state;
}

/**
 * Init a destination through the in-flight dedup map: if an init for `name` is
 * already running, return that promise; otherwise start one and register it,
 * clearing the entry when it settles. Callers that only want a READY handle
 * (getSmartAgent) must check `agentHandles` first — this always (re)runs
 * `initDestination` when nothing is in flight, which is what refresh/retry want.
 */
function ensureDestinationInit(name: string): Promise<DestinationState> {
  const existing = destinationInits.get(name);
  if (existing) return existing;
  const p = initDestination(name).finally(() => {
    destinationInits.delete(name);
  });
  destinationInits.set(name, p);
  return p;
}

/**
 * Initialize remaining destinations in background (after primary is ready).
 * Fetches available SAP destinations from BTP Destination Service and
 * vectorizes each one's MCP tools into a separate RAG store.
 */
async function initBackgroundDestinations(): Promise<void> {
  const log = cds.log('agent-manager');

  try {
    const destinations = await getAvailableDestinations();
    // No privileged primary: warm ALL destinations. The configured
    // LLM_AGENT_MCP_DESTINATION is only an optional "warm this first" hint —
    // it is initialized like any other, just earlier in the queue.
    const hint = getAgentConfig().mcp.destination;
    const ordered = hint
      ? [
          ...destinations.filter((d) => d.name === hint),
          ...destinations.filter((d) => d.name !== hint),
        ]
      : destinations;

    if (ordered.length === 0) {
      log.info('No destinations to initialize');
      return;
    }

    log.info('Starting background destination warmup', {
      destinations: ordered.map((d) => d.name),
      warmFirst: hint || null,
    });

    // Register all destinations as 'pending' immediately so UI sees the full list
    for (const dest of ordered) {
      if (!destinationStates.has(dest.name)) {
        destinationStates.set(dest.name, {
          mcpAdapter: null,
          toolsRag: new ExpositionFilteringRag(new InMemoryRag()),
          toolCount: 0,
          status: 'pending',
          proxyType: dest.proxyType,
          requiresCredentials: destinationRequiresCredentials(
            dest.proxyType,
            dest.authentication,
          ),
        });
      }
    }

    // Sequential: each destination does embedding calls, avoid overwhelming the
    // embedding API. (No destination-level concurrency limit today; a later
    // change can add LLM_AGENT_DEST_INIT_CONCURRENCY if this proves too slow.)
    for (const dest of ordered) {
      const state = destinationStates.get(dest.name);
      if (state?.status === 'ready') continue;
      await ensureDestinationInit(dest.name);
    }

    const states = [...destinationStates.values()];
    log.info('Background destination initialization complete', {
      total: destinationStates.size,
      ready: states.filter((s) => s.status === 'ready').length,
      unreachable: states.filter((s) => s.status === 'unreachable').length,
      errors: states.filter((s) => s.status === 'error').length,
    });

    // Schedule periodic retry for unreachable destinations
    scheduleUnreachableRetry();
  } catch (err) {
    log.warn('Background destination initialization failed', {
      error: err instanceof Error ? err.message : String(err),
    });
  }
}

/** Periodically retry unreachable destinations (every 5 min) */
const UNREACHABLE_RETRY_INTERVAL_MS = 5 * 60 * 1000;
let unreachableRetryTimer: ReturnType<typeof setInterval> | null = null;

function scheduleUnreachableRetry(): void {
  if (unreachableRetryTimer) return;
  const log = cds.log('agent-manager');

  unreachableRetryTimer = setInterval(async () => {
    const unreachable = [...destinationStates.entries()].filter(
      ([, s]) => s.status === 'unreachable',
    );
    if (unreachable.length === 0) {
      // All destinations reachable — stop retrying
      if (unreachableRetryTimer) {
        clearInterval(unreachableRetryTimer);
        unreachableRetryTimer = null;
      }
      return;
    }

    log.info('Retrying unreachable destinations', {
      destinations: unreachable.map(([name]) => name),
    });

    for (const [name] of unreachable) {
      await ensureDestinationInit(name);
      const state = destinationStates.get(name);
      if (state?.status === 'ready') {
        log.info('Previously unreachable destination is now ready', {
          destination: name,
          toolCount: state.toolCount,
        });
      }
    }
  }, UNREACHABLE_RETRY_INTERVAL_MS);
}

/**
 * Build embedded MCP client (in-process, no HTTP).
 *
 * Uses HandlerExporter to get tool definitions and handlers directly,
 * then wraps them in MCPClientWrapper with `transport: 'embedded'`.
 * Connection is resolved from BTP Destination and injected as handler context.
 */
async function buildEmbeddedMcpAdapter(
  destinationName: string,
): Promise<McpClientAdapter> {
  const log = cds.log('agent-manager');

  // Resolve destination metadata for proxy type/system type only. Do not probe
  // or connect here: on-premise destinations must not use a destination service
  // user at startup. Real ABAP credentials are supplied per request.
  await resolveDestinationSapConfig(destinationName);

  setSystemContext({});

  // Load ALL tool handlers — role-based filtering happens at RAG query time
  // via ExpositionFilteringRag (post-filter by exposition metadata).
  // Low-level handlers excluded: they duplicate high-level with finer granularity.
  const exporter = new HandlerExporter(getHandlerExporterConfig());

  const entries = exporter.getHandlerEntries();

  // Handler context with a placeholder connection. Every actual tool call below
  // must receive a per-request connection via connectionALS.
  const context: HandlerContext = {
    connection:
      null as unknown as import('@mcp-abap-adt/interfaces').IAbapConnection,
    logger: loggerAdapter,
  };

  // Inject real connection into handler groups so closure-based handlers (handler.length === 1)
  // use our connection instead of dummyContext (connection: null).
  // HandlerExporter creates groups with dummyContext; BaseMcpServer.registerHandlers() fixes this
  // by setting group.context before calling, but we bypass that — so we do it here.
  // biome-ignore lint/suspicious/noExplicitAny: accessing private handlerGroups field
  const handlerGroups = (exporter as any).handlerGroups as Array<{
    context: HandlerContext;
  }>;
  if (handlerGroups) {
    for (const group of handlerGroups) {
      group.context = context;
    }
  }

  // Build handler map (handlers now use updated group.context via closure)
  const handlerMap = new Map(
    entries.map((e) => [e.toolDefinition.name, e.handler]),
  );

  log.info('Building embedded MCP client', {
    destination: destinationName,
    connectionType: 'per-request',
    toolCount: entries.length,
    tools: exporter.getToolNames(),
  });

  // Named dispatcher so cloud-local tools can recurse by name (GetDumpSection
  // fetches the formatted dump via RuntimeGetDumpById through this same path).
  // biome-ignore lint/suspicious/noExplicitAny: MCP tool args are untyped at this boundary
  async function invokeEmbeddedTool(name: string, args: any): Promise<unknown> {
    // Cloud-local tool: NOT in handlerMap, so branch BEFORE the unknown-tool
    // check. Principal-scoped via the ALS dumpScope; the raw login is never in
    // the key/log — only its hash.
    // Only intercept when core does NOT own this name — consistent with the
    // corpus/listTools dedupe where a future core GetDumpSection wins.
    if (name === 'GetDumpSection' && !handlerMap.has('GetDumpSection')) {
      const dumpScope = connectionALS.getStore()?.dumpScope;
      log.info('GetDumpSection dispatch', {
        destination: destinationName,
        principalHash: dumpScope?.principalHash,
        hasScope: !!dumpScope,
      });
      return handleGetDumpSectionCall(
        { dumpId: args?.dump_id, section: args?.section },
        {
          dumpScope,
          buffer: getDumpBuffer(),
          fetchFormatted: (id: string) =>
            invokeEmbeddedTool('RuntimeGetDumpById', {
              dump_id: id,
              view: 'formatted',
              response_mode: 'payload',
            }).then(parseFormattedDumpPayload),
        },
      );
    }

    const handler = handlerMap.get(name);
    if (!handler) {
      throw new Error(`Unknown MCP tool: ${name}`);
    }
    // Per-request connection override: if ALS has a connection, use it
    // instead of any shared/service-user destination connection.
    const requestScope = connectionALS.getStore();
    if (!requestScope) {
      throw new Error(
        `SAP credentials are required for destination "${destinationName}".`,
      );
    }
    const effectiveContext = requestScope.context;

    // For closure-based handlers, temporarily swap group.context
    // so they pick up per-request connection.
    let prevGroupContexts: HandlerContext[] | undefined;
    try {
      if (requestScope && handlerGroups) {
        prevGroupContexts = handlerGroups.map((g) => g.context);
        for (const g of handlerGroups) {
          g.context = effectiveContext;
        }
      }

      // Handlers from HandlerExporter have two signatures:
      // - length >= 2: (context, args) => ... (direct handlers)
      // - length === 1: (args) => ... (closure-based, uses group.context)
      // Match BaseMcpServer.registerHandlers() logic (line 283-301)
      const toolCall =
        handler.length >= 2
          ? handler(effectiveContext, args)
          : (handler as unknown as (a: typeof args) => unknown)(args);

      // No cloud-llm-hub-side timeout wrapper. Each SAP call is already bounded
      // by the adt-clients HTTP timeout (SAP_TIMEOUT_*), and destination
      // availability is covered by the ProbeDestination reachability check —
      // a redundant Promise.race here only fought those legitimate limits
      // (e.g. cutting heavy where-used scans that the ABAP layer allows).
      const result = await toolCall;

      const resultStr = JSON.stringify(result).slice(0, 1000);
      log.info('MCP tool call', {
        destination: destinationName,
        tool: name,
        handlerType: handler.length >= 2 ? 'direct' : 'closure',
        argsKeys: Object.keys(args || {}),
        args: JSON.stringify(args).slice(0, 300),
        resultLength: resultStr.length,
        resultPreview: resultStr.slice(0, 500),
        connectionOverride: !!requestScope,
      });
      return result;
    } catch (err) {
      log.error('MCP tool call failed', {
        tool: name,
        args: JSON.stringify(args).slice(0, 500),
        error: err instanceof Error ? err.message : String(err),
      });
      throw err;
    } finally {
      // Restore shared group.context after per-request override
      if (prevGroupContexts && handlerGroups) {
        for (let i = 0; i < handlerGroups.length; i++) {
          handlerGroups[i].context = prevGroupContexts[i];
        }
      }
    }
  }

  // Use embedded transport — direct in-process handler calls
  const mcpClient = new MCPClientWrapper({
    transport: 'embedded',
    listToolsHandler: async () => {
      const list = entries.map((e) => ({
        name: e.toolDefinition.name,
        description: e.toolDefinition.description,
        inputSchema: toJsonSchema(e.toolDefinition.inputSchema),
      }));
      // Append cloud-local GetDumpSection unless a core tool already claims the
      // name (same dedupe policy as the corpus). Its inputSchema is already a
      // JSON schema, so it is NOT run through toJsonSchema.
      if (!entries.some((e) => e.toolDefinition.name === 'GetDumpSection')) {
        const def = CLOUD_LOCAL_TOOLS[0];
        list.push({
          name: def.name,
          description: def.description ?? '',
          inputSchema: def.inputSchema as ReturnType<typeof toJsonSchema>,
        });
      }
      return list;
    },
    callToolHandler: async (name, args) => invokeEmbeddedTool(name, args),
  });

  // connect() populates internal tools list from listToolsHandler
  await mcpClient.connect();

  return new McpClientAdapter(mcpClient);
}

/** Create shared LLM instances (called once, reused across all agents) */
function getOrCreateSharedLlms(config: AgentConfig): {
  mainLlm: ReturnType<typeof makeLlm>;
  classifierLlm: ReturnType<typeof makeLlm>;
} {
  if (!sharedMainLlm) {
    const mainModel = getCurrentModel();
    sharedMainLlm = makeLlm(
      {
        provider: config.llm.provider,
        apiKey: config.llm.apiKey || 'sap-ai-sdk-managed',
        baseURL: config.llm.baseUrl,
        model: mainModel,
        temperature: config.llm.temperature,
        maxTokens: config.llm.maxTokens,
        resourceGroup: config.llm.resourceGroup,
      },
      config.llm.temperature,
    );
  }
  if (!sharedClassifierLlm) {
    const classifierModel =
      process.env.LLM_AGENT_CLASSIFIER_MODEL || config.llm.model;
    sharedClassifierLlm = makeLlm(
      {
        provider: config.llm.provider,
        apiKey: config.llm.apiKey || 'sap-ai-sdk-managed',
        baseURL: config.llm.baseUrl,
        model: classifierModel,
        maxTokens: config.llm.maxTokens,
        resourceGroup: config.llm.resourceGroup,
      },
      0.1,
    );
  }
  return {
    mainLlm: sharedMainLlm,
    classifierLlm: sharedClassifierLlm,
  };
}

/**
 * Shared builder configuration for destination-bound SmartAgents — the tool
 * loop, tool RAG, skills pool, MCP tools, and resilience/caching knobs common
 * to BOTH `buildAgentForDestination` (today's single coordinator-less agent)
 * and `buildExecutorWorker` (Task 7's coordinator-less executor worker), so
 * the two build paths cannot drift. Deliberately stops short of `.build()` —
 * callers add any build-specific wiring (e.g. `withRequestLogger`) and build.
 */
async function configureDestinationAgentBuilder(
  mcpAdapter: McpClientAdapter,
  toolsRag: ExpositionFilteringRag,
  config: AgentConfig,
  opts?: { skipSkills?: boolean },
): Promise<SmartAgentBuilder> {
  const { mainLlm: mainLlmPromise, classifierLlm: classifierLlmPromise } =
    getOrCreateSharedLlms(config);
  const mainLlm = await mainLlmPromise;
  const classifierLlm = await classifierLlmPromise;

  // Skip SAP AI SDK model validation for non-SAP providers (openai, anthropic, deepseek)
  const skipModelValidation = config.llm.provider !== 'sap-ai-sdk';

  const builder = new SmartAgentBuilder({
    skipModelValidation,
    agent: {
      maxIterations: config.agent.maxIterations,
      mode: config.agent.mode,
      historyRecencyWindow: config.agent.historyRecencyWindow,
      refreshToolsPerIteration: false,
      toolReselectPerIteration: true,
      ragQueryK: config.agent.ragQueryK,
      // Disable classifier — all input treated as action. Ensures tool search always runs.
      classificationEnabled: false,
    },
    prompts: {
      system: [
        'Use MCP tools when they can accomplish the task. Answer or fulfill requests when possible.',
        'When an action is impossible with available tools — say so and do not attempt it.',
        "Respond in the user's language. Code and object names always in English.",
      ].join('\n'),
      classifier: [
        'You are a Semantic Intent Analyzer. Decompose the user message into logical tasks.',
        'For each task, identify:',
        '  - "type": action (tasks, knowledge questions, SAP operations) or chat (greetings, math, jokes).',
        '  - "text": the actual task description.',
        '  - "context": "sap-abap" if SAP terms present, otherwise "general".',
        '  - "dependency": "independent" or "sequential".',
        '',
        'Rules:',
        '- Multi-step requests: split into separate "action" subprompts with "sequential" dependency.',
        '- Independent tasks: separate subprompts with "independent" dependency.',
        '- Knowledge/factual questions MUST be "action" — NOT "chat".',
        '- Requests to read, list, show, check, analyze, or get any data = "action".',
        '- Only greetings ("hi", "hello"), pure math, and jokes without data requests = "chat".',
        '',
        'Return ONLY a JSON array.',
      ].join('\n'),
    },
  })
    .withMainLlm(mainLlm)
    .withClassifierLlm(classifierLlm)
    .withMcpClients([mcpAdapter]);

  // Tools RAG store for MCP tool selection (auto-vectorized)
  builder.setToolsRag(toolsRag);

  // Mandatory skill pool. The builder vectorizes each skill into toolsRag as
  // `skill:<name>` = "Skill: <name>\n<description>" and the hardcoded flow
  // injects the matched skill's body into the system message. Wired here (agent
  // level), so chat and execute_step behave identically.
  //
  // Skipped when `opts.skipSkills` is set — the DAG controller build (see
  // `buildAgentForDestination`) has its tool-loop stage gated off whenever a
  // coordinator is active (`default-pipeline.js`: `{id:'tool-loop',
  // when:'!coordinatorActive'}`), so the controller never consults skills.
  // Vectorizing them there is a wasted real embedding call (18 skills) on
  // every destination init and regresses cold-start; the executor worker
  // (which DOES run the tool-loop) keeps skills enabled.
  if (!opts?.skipSkills) {
    const skillsPool = buildSkillsPool();
    builder.withSkillManager(skillsPool);
    await logSkillsPool(skillsPool);
  }

  // Share embedder across all RAG queries
  if (sharedEmbedder) builder.withEmbedder(sharedEmbedder);

  builder
    .withClassification(false) // Disable classifier — treat all input as action.
    // Classifier caused tool selection to be skipped for "chat" queries.
    // Without classifier, RAG query + tool selection always runs.
    .withLlmCallStrategy(new FallbackLlmCallStrategy())
    .withToolReselection(true)
    .withToolCache(new ToolCache({ ttlMs: 30_000 }))
    .withMetrics(metrics)
    .withSessionManager(new SessionManager({ tokenBudget: 8000 }))
    .withHistorySummarization(20)
    .withClientAdapter(new ClineClientAdapter());

  // Default hardcoded flow — matches PoC for minimal token overhead.
  // Tools store wrapped with ExpositionFilteringRag to strip ragFilter
  // (tools have no namespace, but opts carry ragFilter for user isolation).

  return builder;
}

/**
 * Build a SmartAgent for a specific destination.
 * Shares LLM, embedder, facts/feedback/state RAG, metrics across all agents.
 */
export async function buildAgentForDestination(
  mcpAdapter: McpClientAdapter,
  toolsRag: ExpositionFilteringRag,
  config: AgentConfig,
): Promise<SmartAgentHandle> {
  const log = cds.log('agent-manager');

  // Self-contained per-trace logger (Task 2) — a plain `DefaultRequestLogger`
  // would wipe telemetry on the nested controller->worker `startRequest` call
  // (Verified fact 10). The SAME instance is injected into the executor
  // worker AND the finalizer so the finalizer's ground truth reflects the
  // tools the worker actually executed (Verified fact 9).
  const recLogger = new RecordingRequestLogger();
  const executorWorker = await buildExecutorWorker(
    mcpAdapter,
    toolsRag,
    config,
    recLogger,
  );

  // Same shared main LLM the rest of the destination agent uses — no extra
  // provider client stood up just for the critic layer.
  const { mainLlm: mainLlmPromise } = getOrCreateSharedLlms(config);
  const criticLlm = await mainLlmPromise;

  // Controller build skips skills — its tool-loop stage is gated off
  // whenever the DAG coordinator is active, so the controller never
  // consults the skills pool (see `configureDestinationAgentBuilder`).
  // Only the executor worker above needs the real skill vectorization.
  const builder = await configureDestinationAgentBuilder(
    mcpAdapter,
    toolsRag,
    config,
    { skipSkills: true },
  );

  builder.withRequestLogger(recLogger).withDagCoordinator({
    planner: new FixedExecutorPlanner(),
    interpreter: new DagPlanInterpreter(),
    // Key MUST be 'executor' — FixedExecutorPlanner hardcodes `agent:
    // 'executor'` on the single DAG node; a mismatched key makes the
    // interpreter throw PLAN_INVALID.
    workers: new Map([['executor', executorWorker]]),
    // Reads the SAME recLogger the worker was built with.
    finalizer: new NoticeFinalizer(recLogger, criticLlm),
    // errorStrategy omitted -> AbortErrorStrategy default;
    // reviewer omitted -> no plan-gate (NoopReviewStrategy default).
  });

  const handle = await builder.build();

  // Expose the recLogger on the handle so channel handlers (Task 11) can
  // call `recLogger.dropRequest(traceId)` in their `finally` block — nobody
  // else drops it, so the per-trace bucket would otherwise leak.
  (
    handle as SmartAgentHandle & { recLogger?: RecordingRequestLogger }
  ).recLogger = recLogger;

  // Diagnostic: confirm structured pipeline is active
  // biome-ignore lint/suspicious/noExplicitAny: diagnostic access to private fields
  const agentObj = handle.agent as any;
  log.info('SmartAgent pipeline diagnostic', {
    hasPipelineExecutor: !!agentObj.pipelineExecutor,
    hasPipelineStages: !!agentObj.pipelineStages,
    stageCount: agentObj.pipelineStages?.length ?? 0,
    stageIds: agentObj.pipelineStages?.map((s: { id: string }) => s.id) ?? [],
    ragStoreKeys: Object.keys(handle.ragStores),
    refreshToolsPerIteration: agentObj.config?.refreshToolsPerIteration,
    toolReselectPerIteration: agentObj.config?.toolReselectPerIteration,
    ragQueryK: agentObj.config?.ragQueryK,
    hasDagCoordinator: true,
  });

  return handle;
}

/**
 * Build the coordinator-less executor worker (Task 7) — the SAME tool-loop
 * SmartAgent configuration as `buildAgentForDestination` (via the shared
 * `configureDestinationAgentBuilder` helper), MINUS any coordinator, PLUS
 * `withRequestLogger(recLogger)` so the worker's internal ABAP tool calls
 * land in the shared `RecordingRequestLogger` (Verified fact 9 —
 * `SmartAgentSubAgent.run` does not forward a requestLogger to the wrapped
 * agent, so it must be injected at build time). Wrapped as an `ISubAgent` by
 * reusing the library's own `SmartAgentSubAgent` — no bespoke wrapper.
 */
export async function buildExecutorWorker(
  mcpAdapter: McpClientAdapter,
  toolsRag: ExpositionFilteringRag,
  config: AgentConfig,
  recLogger: IRequestLogger,
): Promise<ISubAgent> {
  const builder = await configureDestinationAgentBuilder(
    mcpAdapter,
    toolsRag,
    config,
  );
  builder.withRequestLogger(recLogger);

  const handle = await builder.build();
  return new SmartAgentSubAgent('executor', handle.agent);
}

